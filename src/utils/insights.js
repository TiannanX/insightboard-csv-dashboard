import { formatCurrency, formatNumber, formatPercent } from './formatters';

export function generateInsights(data) {
  if (!data || data.length === 0) return [];

  const insights = [];

  // Total revenue by category
  const revenueByCategory = {};
  data.forEach(row => {
    const cat = row.category || 'Unknown';
    revenueByCategory[cat] = (revenueByCategory[cat] || 0) + row.revenue;
  });
  const topCategory = Object.entries(revenueByCategory).sort((a, b) => b[1] - a[1])[0];

  // Highest revenue day
  const revenueByDate = {};
  data.forEach(row => {
    const date = row.date;
    revenueByDate[date] = (revenueByDate[date] || 0) + row.revenue;
  });
  const topDate = Object.entries(revenueByDate).sort((a, b) => b[1] - a[1])[0];

  // Profit by region
  const profitByRegion = {};
  data.forEach(row => {
    const region = row.region || 'Unknown';
    const profit = row.revenue - row.cost;
    profitByRegion[region] = (profitByRegion[region] || 0) + profit;
  });
  const topRegionEntry = Object.entries(profitByRegion).sort((a, b) => b[1] - a[1])[0];

  // Total revenue and cost
  const totals = data.reduce((acc, row) => ({
    revenue: acc.revenue + row.revenue,
    cost: acc.cost + row.cost,
    units: acc.units + row.units,
  }), { revenue: 0, cost: 0, units: 0 });

  // Best selling product (by units)
  const unitsByProduct = {};
  data.forEach(row => {
    const product = row.product || 'Unknown';
    unitsByProduct[product] = (unitsByProduct[product] || 0) + row.units;
  });
  const bestSeller = Object.entries(unitsByProduct).sort((a, b) => b[1] - a[1])[0];

  // Average order value
  const avgOrderValue = totals.revenue / data.length;

  // Gross margin
  const grossMargin = totals.revenue > 0 ? ((totals.revenue - totals.cost) / totals.revenue) * 100 : 0;

  // Build insights array
  insights.push({
    label: 'Top category by revenue',
    value: topCategory ? `${topCategory[0]} (${formatCurrency(topCategory[1])})` : 'N/A',
    icon: 'category',
  });

  insights.push({
    label: 'Highest revenue day',
    value: topDate ? `${topDate[0]} (${formatCurrency(topDate[1])})` : 'N/A',
    icon: 'calendar',
  });

  insights.push({
    label: 'Most profitable region',
    value: topRegionEntry ? `${topRegionEntry[0]} (${formatPercent(grossMargin)} margin)` : 'N/A',
    icon: 'location',
  });

  insights.push({
    label: 'Best-selling product',
    value: bestSeller ? `${bestSeller[0]} (${formatNumber(bestSeller[1])} units)` : 'N/A',
    icon: 'star',
  });

  insights.push({
    label: 'Average order value',
    value: formatCurrency(avgOrderValue),
    icon: 'chart',
  });

  insights.push({
    label: 'Gross margin',
    value: formatPercent(grossMargin),
    icon: 'percent',
  });

  return insights;
}

export function generateSummary(data, kpis) {
  const insights = generateInsights(data);
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  let summary = `# Dashboard Summary\n\n`;
  summary += `**Generated:** ${date}\n\n`;
  summary += `## Key Metrics\n\n`;
  summary += `- **Total Revenue:** ${formatCurrency(kpis.totalRevenue)}\n`;
  summary += `- **Total Cost:** ${formatCurrency(kpis.totalCost)}\n`;
  summary += `- **Gross Profit:** ${formatCurrency(kpis.grossProfit)}\n`;
  summary += `- **Gross Margin:** ${formatPercent(kpis.grossMargin)}\n`;
  summary += `- **Total Units:** ${formatNumber(kpis.totalUnits)}\n`;
  summary += `- **Records:** ${formatNumber(kpis.recordCount)}\n\n`;

  summary += `## Insights\n\n`;
  insights.forEach(insight => {
    summary += `- **${insight.label}:** ${insight.value}\n`;
  });

  summary += `\n---\n*Generated by InsightBoard CSV Dashboard*\n`;

  return summary;
}